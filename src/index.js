#!/usr/bin/env node
// MCP server exposing one tool, get_transcript, over stdio.
// stdout carries the protocol messages, so log only to stderr.

import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { z } from 'zod';
import { getTranscript } from './transcript.js';

const server = new McpServer({ name: 'yt-transcripts', version: '1.0.0' });

server.registerTool(
  'get_transcript',
  {
    title: 'Get YouTube transcript',
    description:
      'Returns the transcript of a YouTube video from its captions (manual or auto-generated). ' +
      'Accepts a video URL (watch, youtu.be, shorts, embed) or an 11-character video ID.',
    inputSchema: {
      url: z.string().describe('YouTube video URL or video ID'),
      lang: z
        .string()
        .default('en')
        .describe('Preferred caption language code, e.g. "en", "es". Falls back to any available language.'),
      timestamps: z.boolean().default(false).describe('Prefix each line with its [m:ss] start time'),
    },
  },
  async ({ url, lang, timestamps }) => {
    try {
      const t = await getTranscript(url, { lang, timestamps });
      const header =
        `Title: ${t.title}\n` +
        `Video ID: ${t.videoId}\n` +
        `Language: ${t.language}${t.autoGenerated ? ' (auto-generated)' : ''}\n` +
        `Other languages: ${t.availableLanguages.join(', ')}\n\n`;
      return { content: [{ type: 'text', text: header + t.text }] };
    } catch (e) {
      // isError tells the model the call failed, so it can explain or retry
      // instead of treating the message as a transcript.
      return { content: [{ type: 'text', text: e.message }], isError: true };
    }
  },
);

await server.connect(new StdioServerTransport());
console.error('yt-transcripts MCP server running on stdio');

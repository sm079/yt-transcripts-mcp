// Fetches a YouTube transcript from the video's own caption tracks
// (no speech-to-text). Same approach as a browser extension would use,
// but running in Node, so every URL is absolute.

// Web caption URLs now require a proof-of-origin token, but the ANDROID
// player client still hands out caption URLs that work without one.
const PLAYER_CLIENT = { clientName: 'ANDROID', clientVersion: '20.10.38', androidSdkVersion: 30 };
const USER_AGENT = 'com.google.android.youtube/20.10.38 (Linux; U; Android 11) gzip';

// Accepts a bare 11-char ID or any common YouTube URL shape.
export function parseVideoId(input) {
  const s = String(input).trim();
  if (/^[\w-]{11}$/.test(s)) return s;
  let url;
  try {
    url = new URL(s.includes('://') ? s : `https://${s}`);
  } catch {
    throw new Error(`Not a YouTube URL or video ID: ${s}`);
  }
  const host = url.hostname.replace(/^(www\.|m\.|music\.)/, '');
  let id = null;
  if (host === 'youtu.be') id = url.pathname.slice(1);
  else if (host === 'youtube.com' || host === 'youtube-nocookie.com') {
    id = url.searchParams.get('v') || url.pathname.match(/^\/(?:shorts|embed|live|v)\/([\w-]{11})/)?.[1];
  }
  if (!id || !/^[\w-]{11}/.test(id)) throw new Error(`Could not find a video ID in: ${s}`);
  return id.slice(0, 11);
}

// Prefer human-made captions in the requested language, then auto-generated
// ones in that language, then whatever exists.
function pickTrack(tracks, lang) {
  const manual = tracks.filter((t) => t.kind !== 'asr');
  return (
    manual.find((t) => t.languageCode.startsWith(lang)) ||
    tracks.find((t) => t.languageCode.startsWith(lang)) ||
    manual[0] ||
    tracks[0]
  );
}

function formatTime(ms) {
  const s = Math.floor(ms / 1000);
  const h = Math.floor(s / 3600);
  const mm = String(Math.floor((s % 3600) / 60)).padStart(h ? 2 : 1, '0');
  const ss = String(s % 60).padStart(2, '0');
  return h ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

export async function getTranscript(input, { lang = 'en', timestamps = false } = {}) {
  const videoId = parseVideoId(input);

  const res = await fetch('https://www.youtube.com/youtubei/v1/player?prettyPrint=false', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'User-Agent': USER_AGENT },
    body: JSON.stringify({ context: { client: { ...PLAYER_CLIENT, hl: lang } }, videoId }),
  });
  if (!res.ok) throw new Error(`YouTube player request failed: HTTP ${res.status}`);
  const player = await res.json();

  const status = player?.playabilityStatus;
  if (status?.status && status.status !== 'OK') {
    throw new Error(`Video not available: ${status.reason || status.status}`);
  }
  const tracks = player?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
  if (!tracks.length) throw new Error('This video has no captions');

  const track = pickTrack(tracks, lang);
  const url = new URL(track.baseUrl);
  url.searchParams.set('fmt', 'json3');
  const capRes = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
  if (!capRes.ok) throw new Error(`Caption download failed: HTTP ${capRes.status}`);
  const { events = [] } = await capRes.json();

  const lines = events
    .map((e) => {
      const text = (e.segs || []).map((s) => s.utf8).join('').replace(/\s+/g, ' ').trim();
      if (!text) return null;
      return timestamps ? `[${formatTime(e.tStartMs || 0)}] ${text}` : text;
    })
    .filter(Boolean);
  if (!lines.length) throw new Error('Transcript is empty');

  return {
    videoId,
    title: player?.videoDetails?.title || '',
    language: track.languageCode,
    autoGenerated: track.kind === 'asr',
    availableLanguages: [...new Set(tracks.map((t) => t.languageCode))],
    text: lines.join('\n'),
  };
}
